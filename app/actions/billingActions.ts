export async function getBillingMetrics() {
  const userId = await getCurrentUserId();
  try {
    const allInvoices = await prisma.invoice.findMany({
      where: { userId },
      select: { amount: true, status: true, createdAt: true, approvedAt: true },
    });

    const now = new Date();
    const startOfYear = new Date(now.getFullYear(), 0, 1);

    let outstanding = 0;
    let ytdTotal = 0;
    let draftCount = 0;
    const paymentDays: number[] = [];

    for (const inv of allInvoices) {
      const amt = Number(inv.amount);
      if (inv.status === 'Draft' || inv.status === 'PendingApproval') {
        outstanding += amt;
      }
      if ((inv.status === 'Paid' || inv.status === 'Finalized') && inv.approvedAt) {
        const days = Math.round((inv.approvedAt.getTime() - inv.createdAt.getTime()) / (1000 * 60 * 60 * 24));
        paymentDays.push(days);
      }
      if (inv.createdAt >= startOfYear) {
        ytdTotal += amt;
      }
      if (inv.status === 'Draft') {
        draftCount++;
      }
    }

    const avgDays = paymentDays.length > 0
      ? Math.round(paymentDays.reduce((a, b) => a + b, 0) / paymentDays.length)
      : 24;

    return {
      outstanding,
      ytdTotal,
      draftCount,
      avgDaysToPay: avgDays,
    };
  } catch (error) {
    console.error('Failed to compute billing metrics:', error);
    return { outstanding: 0, ytdTotal: 0, draftCount: 0, avgDaysToPay: 24 };
  }
}

