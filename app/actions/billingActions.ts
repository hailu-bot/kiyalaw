export async function getInvoices(filters?: {
  search?: string; status?: string; sortBy?: string; sortDir?: string; page?: number; clientId?: string;
}) {
  const userId = await getCurrentUserId();
  try {
    const where: Record<string, unknown> = { userId };

    if (filters?.clientId) where.matter = { clientId: filters.clientId };

    if (filters?.status) {
      const statuses = filters.status.split(',').map(s => s.trim()).filter(Boolean);
      if (statuses.length > 0) where.status = { in: statuses };
    } else {
      where.status = { in: ['Draft', 'PendingApproval'] };
    }

    if (filters?.search) {
      where.clientName = { contains: filters.search, mode: 'insensitive' };
    }

    const pageSize = 15;
    const page = Math.max(1, filters?.page ?? 1);
    const skip = (page - 1) * pageSize;

    const sortFieldMap: Record<string, string> = { invoiceNumber: 'invoiceNumber', amount: 'amount', status: 'status', createdAt: 'createdAt' };
    const sortField = sortFieldMap[filters?.sortBy ?? ''] || 'createdAt';
    const sortDir = filters?.sortDir === 'asc' ? 'asc' : 'desc';

    const [rows, totalCount] = await Promise.all([
      prisma.invoice.findMany({
        where,
        orderBy: { [sortField]: sortDir },
        skip,
        take: pageSize,
        include: {
          matter: { select: { id: true, title: true, clientId: true } },
        },
      }),
      prisma.invoice.count({ where }),
    ]);

    return {
      invoices: rows.map((row) => {
        const amount = Number(row.amount);
        return {
          id: String(row.id),
          invoiceNumber: row.invoiceNumber,
          clientName: row.clientName,
          amount,
          dueDate: row.dueDateLabel,
          status: row.status,
          createdAt: row.createdAt instanceof Date ? row.createdAt.toISOString() : String(row.createdAt),
          matterId: row.matter?.id ?? null,
          matterTitle: row.matter?.title ?? null,
          clientId: row.matter?.clientId ?? null,
        };
      }),
      totalCount,
      page,
      totalPages: Math.ceil(totalCount / pageSize),
    };
  } catch (error) {
    console.error('getInvoices error:', error);
    return { invoices: [], totalCount: 0, page: 1, totalPages: 0 };
  }
}
