export async function generateInvoiceFromTimeEntries(matterId: string, billingPeriodStart?: string, billingPeriodEnd?: string) {
  if (!await requireRole('PARTNER', 'ASSOCIATE')) return null;
  const userId = await getCurrentUserId();
  try {
    const matter = await prisma.matter.findFirst({ where: { id: matterId, userId } });
    if (!matter) return null;

    const unbilled = await prisma.timeEntry.findMany({
      where: { matterId, userId, billable: true, invoiceId: null },
      orderBy: { date: 'asc' },
    });
    if (unbilled.length === 0) return null;

    // Get effective rate from rate cards
    const { getEffectiveRate } = await import('@/app/actions/rateActions');
    const effectiveRate = await getEffectiveRate(matterId, matter.clientId ?? undefined);

    // Build line items — group by description if same, or keep individual
    const lineItems = unbilled.map((te) => ({
      description: te.description,
      hours: Number(te.hours),
      rate: effectiveRate,
      total: Number(te.hours) * effectiveRate,
    }));

    const totalAmount = lineItems.reduce((s, li) => s + li.total, 0);

    // Determine due date from client billing terms
    let dueLabel = 'Upon Receipt';
    if (matter.clientId) {
      const client = await prisma.client.findUnique({ where: { id: matter.clientId } });
      if (client?.billingTerms) {
        const termMap: Record<string, number> = {
          Net15: 15, Net30: 30, Net45: 45, Net60: 60, Net90: 90,
        };
        const days = termMap[client.billingTerms];
        if (days) {
          const due = new Date();
          due.setDate(due.getDate() + days);
          dueLabel = due.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
        }
      }
    }

    const now = Date.now();
    const invoiceNumber = `AUTO-${matter.matterCode}-${now}`;

    const created = await prisma.invoice.create({
      data: {
        userId,
        invoiceNumber,
        matterId,
        clientName: matter.clientName,
        amount: new Prisma.Decimal(totalAmount),
        dueDateLabel: dueLabel,
        status: 'Draft',
        autoGenerated: true,
        billingPeriodStart: billingPeriodStart ? new Date(billingPeriodStart) : unbilled[0].date,
        billingPeriodEnd: billingPeriodEnd ? new Date(billingPeriodEnd) : unbilled[unbilled.length - 1].date,
        notes: 'Auto-generated from unbilled time entries.',
        lineItems: {
          create: lineItems.map((li) => ({
            description: li.description,
            hours: new Prisma.Decimal(li.hours),
            rate: new Prisma.Decimal(li.rate),
            total: new Prisma.Decimal(li.total),
          })),
        },
        timeEntries: {
          connect: unbilled.map((te) => ({ id: te.id })),
        },
      },
      include: { lineItems: true },
    });

    // Mark time entries as billed
    await prisma.timeEntry.updateMany({
      where: { id: { in: unbilled.map((te) => te.id) } },
      data: { billedAt: new Date(), invoiceId: created.id },
    });

    // Update matter's lastBillingDate
    await prisma.matter.update({
      where: { id: matterId },
      data: { lastBillingDate: new Date() },
    });

    revalidatePath('/billing');
    revalidatePath('/');
    return created;
  } catch (error) {
    console.error('generateInvoiceFromTimeEntries error:', error);
    return null;
  }
}

export async function runBillingCycleForUser(userId: string) {
  try {
    const firmProfile = await prisma.firmProfile.findFirst({ orderBy: { createdAt: 'asc' } });
    if (!firmProfile) return { generated: 0, message: 'No firm profile found.' };

    const cycleDays = firmProfile.billingCycleDays;
    const leadDays = firmProfile.billingLeadDays;

    // Find all active matters for this user
    const matters = await prisma.matter.findMany({
      where: { userId, status: 'Active' },
      select: {
        id: true, clientId: true, createdAt: true, lastBillingDate: true,
        billingCycleDays: true,
        _count: { select: { timeEntries: true } },
      },
    });

    const now = new Date();
    let generated = 0;

    for (const matter of matters) {
      // Skip matters with no time entries
      if (matter._count.timeEntries === 0) continue;

      // Check unbilled time entries exist
      const unbilledCount = await prisma.timeEntry.count({
        where: { matterId: matter.id, userId, billable: true, invoiceId: null },
      });
      if (unbilledCount === 0) continue;

      // Determine billing cycle for this matter (matter override or firm default)
      const effectiveCycle = matter.billingCycleDays ?? cycleDays;

      // Last billing date: if never billed, use matter creation date
      const lastDate = matter.lastBillingDate || matter.createdAt;
      const daysSinceLastBill = Math.round((now.getTime() - lastDate.getTime()) / (1000 * 60 * 60 * 24));

      // Check if we have passed the lead-time threshold AND at least one full cycle since last bill
      const triggerDays = effectiveCycle - leadDays;
      if (daysSinceLastBill < triggerDays) continue;
      if (daysSinceLastBill < effectiveCycle && matter.lastBillingDate !== null) continue;

      // Generate the invoice
      const result = await generateInvoiceFromTimeEntries(matter.id);
      if (result) generated++;
    }

    // Update lastBillingRun on firm profile
    await prisma.firmProfile.update({
      where: { id: firmProfile.id },
      data: { lastBillingRun: now },
    });

    revalidatePath('/');
    revalidatePath('/billing');
    return { generated, message: `Billing cycle complete. ${generated} invoice(s) generated.` };
  } catch (error) {
    console.error('runBillingCycle error:', error);
    return { generated: 0, message: 'Billing cycle failed.' };
  }
}

export async function runBillingCycle() {
  const userId = await getCurrentUserId();
  return runBillingCycleForUser(userId);
}

