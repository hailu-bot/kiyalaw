type CreateInvoiceInput = {
  invoiceNumber: string;
  matterId: string;
  clientName?: string;
  amount?: number;
  dueDateLabel?: string;
  status?: Prisma.InvoiceUncheckedCreateInput['status'];
  notes?: string;
  lineItems?: Array<{
    description: string;
    hours: number;
    rate: number;
    total: number;
  }>;
};

export async function createInvoice(data: CreateInvoiceInput) {
  if (!await requireRole('PARTNER', 'ASSOCIATE')) return { success: false as const, error: 'FORBIDDEN', message: 'Forbidden' };
  const userId = await getCurrentUserId();
  const invoiceNumber = String(data.invoiceNumber ?? '').trim();
  const matterId = String(data.matterId ?? '').trim();

  if (!invoiceNumber || !matterId) {
    return { success: false as const, error: 'VALIDATION', message: 'Missing invoice number or matter selection.' };
  }

  try {
    const created = await prisma.invoice.create({
      data: {
        userId,
        invoiceNumber,
        matterId,
        clientName: String(data.clientName ?? ''),
        amount: new Prisma.Decimal(Number(data.amount) || 0),
        dueDateLabel: String(data.dueDateLabel ?? ''),
        notes: data.notes,
        status: 'Draft',
        lineItems: data.lineItems?.length
          ? {
              create: data.lineItems.map((li) => ({
                description: li.description,
                hours: new Prisma.Decimal(li.hours),
                rate: new Prisma.Decimal(li.rate),
                total: new Prisma.Decimal(li.total),
              })),
            }
          : undefined,
      },
      include: { lineItems: true },
    });

    revalidatePath('/billing');
    revalidatePath(`/billing/${created.id}`);

    return {
      success: true as const,
      invoice: {
        id: created.id,
        invoiceNumber: created.invoiceNumber,
        matterId: created.matterId,
        clientName: created.clientName,
        amount: Number(created.amount),
        dueDateLabel: created.dueDateLabel,
        status: created.status,
        createdAt: created.createdAt instanceof Date ? created.createdAt.toISOString() : String(created.createdAt),
      },
    };
  } catch (error) {
    console.error("Prisma Error Details:", error);

    if (error instanceof Prisma.PrismaClientKnownRequestError) {
      if (error.code === 'P2002') {
        return {
          success: false as const,
          error: 'DUPLICATE_INVOICE',
          message: `Invoice number "${invoiceNumber}" already exists for this matter. Please use a different invoice number.`,
        };
      }
      if (error.code === 'P2003') {
        return {
          success: false as const,
          error: 'INVALID_MATTER',
          message: 'The selected matter does not exist. Please choose a valid matter from the list.',
        };
      }
    }

    return { success: false as const, error: 'UNKNOWN', message: 'Database transmission failed. Please inspect input formats.' };
  }
}

